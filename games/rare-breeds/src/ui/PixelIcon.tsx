export type PixelIconName = keyof typeof ICONS;

/** Decorative 1-bit icon. Pixel size is an integer so edges stay crisp. */
export function PixelIcon({ name, pixel = 2, className }: { name: PixelIconName; pixel?: number; className?: string }) {
  const rows = ICONS[name];
  const width = Math.max(...rows.map(row => row.length)), height = rows.length;
  const rects: string[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;
      let run = 1;
      while (row[x + run] === "#") run++;
      rects.push(`M${x} ${y}h${run}v1h-${run}z`);
      x += run - 1;
    }
  });
  return <svg className={cx("rb-icon", className)} width={width * pixel} height={height * pixel} viewBox={`0 0 ${width} ${height}`}
    aria-hidden="true" focusable="false" shapeRendering="crispEdges"><path d={rects.join("")} fill="currentColor" /></svg>;
}
